import { test, expect } from "@playwright/test";
import { readFile } from "node:fs/promises";

test("ผู้ดูแลตรวจ 517465 และเก็บประกาศเปิดสอนเฉพาะภาคพร้อมที่มา", async ({ page }, info) => {
  await page.context().addCookies(JSON.parse(await readFile("tests/.auth/admin.json", "utf8")).cookies);
  await page.goto("/admin/academic");
  await page.getByRole("button", { name: "สร้างร่าง CS2565 เริ่มต้น", exact: true }).click();
  await expect(page.getByText("สร้างร่าง CS2565 แล้ว ตรวจข้อมูลก่อนเผยแพร่", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "เงื่อนไขการเรียน", exact: true }).click();
  await expect(page.getByRole("combobox", { name: "การจัดหมวดวิชาเลือก", exact: true })).toHaveValue("specific_then_free_earliest_pass");
  await page.getByRole("button", { name: "รายวิชา", exact: true }).click();
  await page.getByLabel("ค้นหารหัสหรือชื่อวิชา", { exact: true }).fill("517465");
  await page.getByRole("button", { name: "แก้ 517465", exact: true }).click();
  await expect(page.getByLabel("ชื่อรายวิชา", { exact: true })).toHaveValue("วิศวกรรมคุณลักษณะ");
  await expect(page.getByRole("combobox", { name: "นโยบายเกรดรายวิชา", exact: true })).toHaveValue("numeric");
  await expect(page.getByLabel("แหล่งกฎ / หน้าเอกสาร", { exact: true })).toHaveValue(/คำยืนยันผู้ใช้/);
  await page.getByRole("button", { name: "การเปิดสอน", exact: true }).click();
  await expect(page.getByText(/วิชาเลือกอาจเปิดไม่ตรงกันแต่ละภาค/)).toBeVisible();
  const term = page.getByRole("combobox", { name: "เปิดสอน 517465 ภาค 1", exact: true });
  await expect(term).toHaveValue("unknown");
  await page.getByLabel("แหล่งข้อมูลหรือสมมติฐาน", { exact: true }).fill("Synthetic teacher announcement in Facebook group; 2026-10-17; term 2569/1");
  await term.selectOption("open");
  const row = page.getByRole("row").filter({ hasText: "517465 · วิศวกรรมคุณลักษณะ" });
  const confirmed = row.getByRole("checkbox", { name: "มีแหล่งยืนยัน", exact: true });
  await confirmed.check();
  const source = page.getByLabel("ที่มา 517465 ภาค 1", { exact: true });
  await source.fill("Synthetic revised teacher announcement; 2026-10-17; term 2569/1");
  await expect(confirmed).not.toBeChecked();
  await confirmed.check();
  await page.getByRole("button", { name: "บันทึกร่างข้อมูล", exact: true }).click();
  await expect(page.getByText("บันทึกร่างแล้ว ยังไม่เผยแพร่", { exact: true })).toBeVisible();
  await page.reload();
  await page.getByRole("button", { name: "เงื่อนไขการเรียน", exact: true }).click();
  await expect(page.getByRole("combobox", { name: "การจัดหมวดวิชาเลือก", exact: true })).toHaveValue("specific_then_free_earliest_pass");
  await page.getByRole("button", { name: "รายวิชา", exact: true }).click();
  await page.getByLabel("ค้นหารหัสหรือชื่อวิชา", { exact: true }).fill("517465");
  await page.getByRole("button", { name: "การเปิดสอน", exact: true }).click();
  await expect(term).toHaveValue("open");
  await expect(source).toHaveValue("Synthetic revised teacher announcement; 2026-10-17; term 2569/1");
  await expect(confirmed).toBeChecked();
  await expect(page.getByRole("combobox", { name: "เปิดสอน 517465 ภาค 2", exact: true })).toHaveValue("unknown");
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: `C:/Users/MyLuna/aps-v2-doc/deliverables/evidence/category-agreement/admin-${info.project.name}.png`, fullPage: true });
  await page.getByLabel("ปี พ.ศ.", { exact: true }).fill("2570");
  await expect(term).toHaveValue("unknown");
});
